CREATE TABLE public.learning_path (
    path_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    path_name VARCHAR(100) NOT NULL UNIQUE,

    description TEXT,

    status VARCHAR(20) NOT NULL DEFAULT 'coming_soon'
        CHECK (status IN ('available', 'coming_soon', 'disabled')),

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

