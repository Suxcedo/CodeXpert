    CREATE TABLE public.enrollment (
    enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id)
        ON DELETE CASCADE,

    path_id BIGINT NOT NULL
        REFERENCES public.learning_path(path_id)
        ON DELETE CASCADE,

    enrolled_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),

    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'completed', 'paused')),

    path_xp INTEGER NOT NULL DEFAULT 0
        CHECK (path_xp >= 0),

    current_level INTEGER NOT NULL DEFAULT 1
        CHECK (current_level >= 1),

    UNIQUE (user_id, path_id)
);

CREATE TABLE public.module (
    module_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    path_id BIGINT NOT NULL
        REFERENCES public.learning_path(path_id)
        ON DELETE CASCADE,

    module_number INTEGER NOT NULL
        CHECK (module_number >= 1),

    module_name VARCHAR(150) NOT NULL,

    description TEXT,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),

    UNIQUE (path_id, module_number)
);




