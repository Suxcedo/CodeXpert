-- ============================================================
-- 18. AUTOMATIC QUESTION STATUS
-- When a question receives its first answer,
-- its status changes from unanswered to answered.
-- ============================================================

CREATE FUNCTION public.help_update_post_status_after_reply()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN

    UPDATE public.help_post
    SET status = CASE
        WHEN accepted_reply_id IS NOT NULL THEN 'solved'
        ELSE 'answered'
    END
    WHERE post_id = NEW.post_id;

    RETURN NEW;

END;
$$;


CREATE TRIGGER trg_help_reply_update_post_status
AFTER INSERT ON public.help_reply
FOR EACH ROW
EXECUTE FUNCTION public.help_update_post_status_after_reply();


-- ============================================================
-- 19. NOTIFICATION FOR NEW REPLIES
-- Notify the question owner when another user replies.
-- ============================================================

CREATE FUNCTION public.help_notify_question_owner()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE

    v_owner_id UUID;

    v_question_title VARCHAR(200);

    v_reply_username VARCHAR(50);

BEGIN

    SELECT user_id, title
    INTO v_owner_id, v_question_title
    FROM public.help_post
    WHERE post_id = NEW.post_id;

    -- Do not notify someone about their own reply.

    IF v_owner_id IS NULL OR v_owner_id = NEW.user_id THEN
        RETURN NEW;
    END IF;

    SELECT username
    INTO v_reply_username
    FROM public.user_profile
    WHERE user_id = NEW.user_id;

    INSERT INTO public.notification (
        user_id,
        actor_user_id,
        notification_type,
        title,
        message,
        reference_type,
        reference_id
    )
    VALUES (
        v_owner_id,
        NEW.user_id,
        'help_reply',
        'New reply to your question',
        COALESCE(v_reply_username, 'Someone')
            || ' replied to your question: '
            || LEFT(v_question_title, 100),
        'help_post',
        NEW.post_id
    );

    RETURN NEW;

END;
$$;


CREATE TRIGGER trg_help_reply_notification
AFTER INSERT ON public.help_reply
FOR EACH ROW
EXECUTE FUNCTION public.help_notify_question_owner();


-- ============================================================
-- 20. ACCEPTED ANSWER XP REWARD
-- Award 10 overall XP to the answer author.
-- Each reply can receive this reward only once.
-- ============================================================

CREATE FUNCTION public.help_award_accepted_reply_xp()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE

    v_reply_user_id UUID;

    v_reward_id BIGINT;

    v_question_title VARCHAR(200);

BEGIN

    -- Only process a newly accepted reply.

    IF NEW.accepted_reply_id IS NULL
       OR NEW.accepted_reply_id IS NOT DISTINCT FROM OLD.accepted_reply_id
    THEN
        RETURN NEW;
    END IF;


    -- Verify that the answer belongs to this question.

    SELECT r.user_id, p.title
    INTO v_reply_user_id, v_question_title
    FROM public.help_reply r
    INNER JOIN public.help_post p
        ON p.post_id = r.post_id
    WHERE r.reply_id = NEW.accepted_reply_id
    AND r.post_id = NEW.post_id;


    IF v_reply_user_id IS NULL THEN
        RAISE EXCEPTION
            'The selected reply does not belong to this question.';
    END IF;


    -- Prevent users from accepting their own replies.

    IF v_reply_user_id = NEW.user_id THEN
        RAISE EXCEPTION
            'You cannot accept your own reply.';
    END IF;


    -- Record the reward.
    -- UNIQUE(reply_id) prevents duplicate rewards.

    INSERT INTO public.help_xp_reward (
        reply_id,
        user_id,
        xp_amount
    )
    VALUES (
        NEW.accepted_reply_id,
        v_reply_user_id,
        10
    )
    ON CONFLICT (reply_id) DO NOTHING
    RETURNING reward_id INTO v_reward_id;


    -- Only update XP if a new reward was recorded.

    IF v_reward_id IS NOT NULL THEN

        UPDATE public.user_profile
        SET overall_xp = overall_xp + 10
        WHERE user_id = v_reply_user_id;


        -- Notify the user whose answer was accepted.

        INSERT INTO public.notification (
            user_id,
            actor_user_id,
            notification_type,
            title,
            message,
            reference_type,
            reference_id
        )
        VALUES (
            v_reply_user_id,
            NEW.user_id,
            'help_solution_accepted',
            'Your answer was accepted!',
            'Your reply was accepted as the solution to: '
                || LEFT(v_question_title, 100)
                || '. You earned 10 XP.',
            'help_post',
            NEW.post_id
        );

    END IF;

    RETURN NEW;

END;
$$;


CREATE TRIGGER trg_help_accepted_reply_xp
AFTER UPDATE OF accepted_reply_id ON public.help_post
FOR EACH ROW
EXECUTE FUNCTION public.help_award_accepted_reply_xp();


-- ============================================================
-- 21. ACCEPT A REPLY
-- Only the question owner can accept an answer.
--
-- Authenticated frontend call:
--   help_accept_reply(post_id, reply_id)
--
-- Trusted backend service-role call:
--   help_accept_reply(post_id, reply_id, verified_user_id)
--
-- The backend must verify the user's Supabase access token
-- before passing the verified user ID.
-- ============================================================

CREATE FUNCTION public.help_accept_reply(
    p_post_id BIGINT,
    p_reply_id BIGINT,
    p_actor_user_id UUID DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE

    v_actor_id UUID;

    v_owner_id UUID;

    v_reply_user_id UUID;

    v_current_accepted_reply BIGINT;

BEGIN

    v_actor_id := auth.uid();


    -- Allow trusted backend calls only when the backend
    -- explicitly supplies a verified user ID.

    IF v_actor_id IS NULL THEN

        IF auth.role() <> 'service_role'
           OR p_actor_user_id IS NULL
        THEN
            RAISE EXCEPTION 'Authentication is required.';
        END IF;

        v_actor_id := p_actor_user_id;

    ELSIF p_actor_user_id IS NOT NULL
          AND p_actor_user_id <> v_actor_id
    THEN

        RAISE EXCEPTION 'Invalid user identity.';

    END IF;


    -- Lock the question while processing acceptance.

    SELECT user_id, accepted_reply_id
    INTO v_owner_id, v_current_accepted_reply
    FROM public.help_post
    WHERE post_id = p_post_id
    FOR UPDATE;


    IF v_owner_id IS NULL THEN
        RAISE EXCEPTION 'Question not found.';
    END IF;


    IF v_owner_id <> v_actor_id THEN
        RAISE EXCEPTION
            'Only the question owner can accept a reply.';
    END IF;


    IF v_current_accepted_reply IS NOT NULL
       AND v_current_accepted_reply <> p_reply_id
    THEN
        RAISE EXCEPTION
            'Reopen the question before accepting a different reply.';
    END IF;


    -- Verify the reply belongs to the question.

    SELECT user_id
    INTO v_reply_user_id
    FROM public.help_reply
    WHERE reply_id = p_reply_id
    AND post_id = p_post_id;


    IF v_reply_user_id IS NULL THEN
        RAISE EXCEPTION
            'That reply does not belong to this question.';
    END IF;


    IF v_reply_user_id = v_owner_id THEN
        RAISE EXCEPTION
            'You cannot accept your own reply.';
    END IF;


    UPDATE public.help_post
    SET accepted_reply_id = p_reply_id,
        status = 'solved'
    WHERE post_id = p_post_id;

END;
$$;


-- ============================================================
-- 22. REOPEN A QUESTION
-- The question owner can reopen a solved question.
-- Previously awarded XP is never deducted or awarded again.
-- ============================================================

CREATE FUNCTION public.help_reopen_post(
    p_post_id BIGINT,
    p_actor_user_id UUID DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE

    v_actor_id UUID;

    v_owner_id UUID;

    v_reply_count BIGINT;

BEGIN

    v_actor_id := auth.uid();


    IF v_actor_id IS NULL THEN

        IF auth.role() <> 'service_role'
           OR p_actor_user_id IS NULL
        THEN
            RAISE EXCEPTION 'Authentication is required.';
        END IF;

        v_actor_id := p_actor_user_id;

    ELSIF p_actor_user_id IS NOT NULL
          AND p_actor_user_id <> v_actor_id
    THEN

        RAISE EXCEPTION 'Invalid user identity.';

    END IF;


    SELECT user_id
    INTO v_owner_id
    FROM public.help_post
    WHERE post_id = p_post_id
    FOR UPDATE;


    IF v_owner_id IS NULL THEN
        RAISE EXCEPTION 'Question not found.';
    END IF;


    IF v_owner_id <> v_actor_id THEN
        RAISE EXCEPTION
            'Only the question owner can reopen it.';
    END IF;


    SELECT COUNT(*)
    INTO v_reply_count
    FROM public.help_reply
    WHERE post_id = p_post_id;


    UPDATE public.help_post
    SET accepted_reply_id = NULL,
        status = CASE
            WHEN v_reply_count > 0 THEN 'answered'
            ELSE 'unanswered'
        END
    WHERE post_id = p_post_id;

END;
$$;


