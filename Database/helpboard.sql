-- ============================================================
-- 1. HELP POST
-- Stores questions submitted by users.
-- ============================================================

CREATE TABLE public.help_post (

    post_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id UUID NOT NULL DEFAULT auth.uid()
        REFERENCES public.user_profile(user_id)
        ON DELETE RESTRICT,

    title VARCHAR(200) NOT NULL,

    description TEXT NOT NULL,

    programming_language VARCHAR(50) NOT NULL,

    difficulty_level VARCHAR(20),

    status VARCHAR(20) NOT NULL DEFAULT 'unanswered',

    accepted_reply_id BIGINT,

    view_count INTEGER NOT NULL DEFAULT 0,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT help_post_title_not_empty
        CHECK (LENGTH(TRIM(title)) > 0),

    CONSTRAINT help_post_description_not_empty
        CHECK (LENGTH(TRIM(description)) > 0),

    CONSTRAINT help_post_language_not_empty
        CHECK (LENGTH(TRIM(programming_language)) > 0),

    CONSTRAINT help_post_status_check
        CHECK (
            status IN ('unanswered', 'answered', 'solved')
        ),

    CONSTRAINT help_post_difficulty_check
        CHECK (
            difficulty_level IS NULL
            OR difficulty_level IN (
                'beginner',
                'intermediate',
                'advanced'
            )
        ),

    CONSTRAINT help_post_view_count_check
        CHECK (view_count >= 0)
);


-- ============================================================
-- 2. HELP REPLY
-- Stores answers submitted to questions.
-- ============================================================

CREATE TABLE public.help_reply (

    reply_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    post_id BIGINT NOT NULL
        REFERENCES public.help_post(post_id)
        ON DELETE CASCADE,

    user_id UUID NOT NULL DEFAULT auth.uid()
        REFERENCES public.user_profile(user_id)
        ON DELETE RESTRICT,

    reply_text TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT help_reply_text_not_empty
        CHECK (LENGTH(TRIM(reply_text)) > 0)
);


