BEGIN;

-- 1. STREAK
-- Stores each learner's current and longest streak.

CREATE TABLE public.streak (
    streak_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL UNIQUE
        REFERENCES public.user_profile(user_id) ON DELETE CASCADE,
    current_streak INTEGER NOT NULL DEFAULT 0
        CHECK (current_streak >= 0),
    longest_streak INTEGER NOT NULL DEFAULT 0
        CHECK (longest_streak >= 0),
    last_activity_date DATE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT streak_longest_check
        CHECK (longest_streak >= current_streak)
);


-- 2. DAILY_ACTIVITY
-- Stores lesson activity for each learner on each date.

CREATE TABLE public.daily_activity (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id) ON DELETE CASCADE,
    activity_date DATE NOT NULL DEFAULT CURRENT_DATE,
    lessons_completed INTEGER NOT NULL DEFAULT 0
        CHECK (lessons_completed >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT daily_activity_user_date_unique
        UNIQUE (user_id, activity_date)
);


-- 3. BADGE
-- Stores available achievements and streak milestones.

CREATE TABLE public.badge (
    badge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    badge_name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    badge_category VARCHAR(30) NOT NULL
        CHECK (badge_category IN ('STREAK', 'LEARNING', 'XP')),
    requirement_value INTEGER NOT NULL
        CHECK (requirement_value > 0),
    image_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- 4. USER_BADGE
-- Records badges earned by learners.

CREATE TABLE public.user_badge (
    user_badge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id) ON DELETE CASCADE,
    badge_id BIGINT NOT NULL
        REFERENCES public.badge(badge_id) ON DELETE CASCADE,
    earned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT user_badge_unique
        UNIQUE (user_id, badge_id)
);


-- 5. REWARD
-- Stores rewards associated with achievements.

CREATE TABLE public.reward (
    reward_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reward_code VARCHAR(100) NOT NULL UNIQUE,
    reward_name VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    reward_type VARCHAR(30) NOT NULL
        CHECK (reward_type IN ('XP_BONUS', 'TITLE')),
    requirement_category VARCHAR(30) NOT NULL
        CHECK (requirement_category IN ('STREAK', 'LEARNING', 'XP')),
    requirement_value INTEGER NOT NULL
        CHECK (requirement_value > 0),
    reward_value TEXT NOT NULL,
    image_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- 6. USER_REWARD
-- Records rewards earned and claimed by learners.

CREATE TABLE public.user_reward (
    user_reward_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id) ON DELETE CASCADE,
    reward_id BIGINT NOT NULL
        REFERENCES public.reward(reward_id) ON DELETE CASCADE,
    earned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    claimed_at TIMESTAMPTZ,
    reward_status VARCHAR(20) NOT NULL DEFAULT 'EARNED'
        CHECK (reward_status IN ('EARNED', 'CLAIMED')),

    CONSTRAINT user_reward_unique
        UNIQUE (user_id, reward_id),

    CONSTRAINT user_reward_claimed_check
        CHECK (
            (reward_status = 'EARNED' AND claimed_at IS NULL)
            OR
            (reward_status = 'CLAIMED' AND claimed_at IS NOT NULL)
        )
);


-- INDEXES
-- Improve lookups when loading learner achievements and activity.

CREATE INDEX idx_daily_activity_user_date
    ON public.daily_activity(user_id, activity_date DESC);

CREATE INDEX idx_user_badge_user
    ON public.user_badge(user_id);

CREATE INDEX idx_user_reward_user
    ON public.user_reward(user_id);

CREATE INDEX idx_badge_category
    ON public.badge(badge_category);

CREATE INDEX idx_reward_requirement
    ON public.reward(requirement_category, requirement_value);


COMMIT;




