CREATE OR REPLACE FUNCTION public.process_lesson_completion(
    p_user_id UUID,
    p_lesson_id BIGINT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_timezone VARCHAR(100);
    v_activity_date DATE;
    v_completed_at TIMESTAMPTZ;
    v_path_id BIGINT;
    v_lessons_completed INTEGER := 0;

    v_current_streak INTEGER := 0;
    v_longest_streak INTEGER := 0;
    v_last_activity_date DATE;

    v_badge public.badge%ROWTYPE;
    v_reward public.reward%ROWTYPE;

    v_inserted_badge_id BIGINT;
    v_inserted_reward_id BIGINT;

    v_new_badges JSONB := '[]'::JSONB;
    v_new_rewards JSONB := '[]'::JSONB;

    v_awarded BOOLEAN;
    v_awarded_amount INTEGER;
    v_bonus_xp INTEGER := 0;
    v_overall_xp INTEGER := 0;
    v_path_xp INTEGER := 0;
BEGIN
    -- Get and validate the learner's timezone.
    SELECT timezone
    INTO v_timezone
    FROM public.user_profile
    WHERE user_id = p_user_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'User profile not found.';
    END IF;

    IF v_timezone IS NULL OR NOT EXISTS (
        SELECT 1
        FROM pg_timezone_names
        WHERE name = v_timezone
    ) THEN
        v_timezone := 'Africa/Johannesburg';
    END IF;

    -- Confirm that the lesson belongs to a learning path.
    SELECT m.path_id
    INTO v_path_id
    FROM public.lesson l
    JOIN public.module m ON m.module_id = l.module_id
    WHERE l.lesson_id = p_lesson_id
      AND l.status = 'published';

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Published lesson not found.';
    END IF;

    -- Confirm that the learner has an active enrollment.
    IF NOT EXISTS (
        SELECT 1
        FROM public.enrollment
        WHERE user_id = p_user_id
          AND path_id = v_path_id
          AND status = 'active'
    ) THEN
        RAISE EXCEPTION 'Active enrollment not found.';
    END IF;

    -- Only completed lessons can contribute to a streak.
    SELECT completed_at
    INTO v_completed_at
    FROM public.lesson_progress
    WHERE user_id = p_user_id
      AND lesson_id = p_lesson_id
      AND status = 'completed';

    IF NOT FOUND OR v_completed_at IS NULL THEN
        RAISE EXCEPTION 'The lesson has not been completed.';
    END IF;

    -- Convert the completion timestamp to the learner's local date.
    v_activity_date := (v_completed_at AT TIME ZONE v_timezone)::DATE;

    -- Count distinct completed lessons for this learner on this local date.
    SELECT COUNT(*)::INTEGER
    INTO v_lessons_completed
    FROM public.lesson_progress
    WHERE user_id = p_user_id
      AND status = 'completed'
      AND completed_at IS NOT NULL
      AND (completed_at AT TIME ZONE v_timezone)::DATE = v_activity_date;

    -- Save or refresh the learner's daily activity.
    INSERT INTO public.daily_activity (
        user_id,
        activity_date,
        lessons_completed
    )
    VALUES (
        p_user_id,
        v_activity_date,
        v_lessons_completed
    )
    ON CONFLICT (user_id, activity_date)
    DO UPDATE SET
        lessons_completed = EXCLUDED.lessons_completed;

    -- Create the streak record if this is the learner's first completed lesson.
    INSERT INTO public.streak (user_id)
    VALUES (p_user_id)
    ON CONFLICT (user_id) DO NOTHING;

    -- Lock the streak record so simultaneous requests cannot increment it twice.
    SELECT
        current_streak,
        longest_streak,
        last_activity_date
    INTO
        v_current_streak,
        v_longest_streak,
        v_last_activity_date
    FROM public.streak
    WHERE user_id = p_user_id
    FOR UPDATE;

    -- Update the streak only when this is a new local activity date.
    IF v_last_activity_date IS NULL THEN
        v_current_streak := 1;
        v_last_activity_date := v_activity_date;

    ELSIF v_activity_date = v_last_activity_date THEN
        -- Another lesson was completed on the same day.
        -- Do not increase the streak again.

        NULL;

    ELSIF v_activity_date = v_last_activity_date + 1 THEN
        v_current_streak := v_current_streak + 1;
        v_last_activity_date := v_activity_date;

    ELSIF v_activity_date > v_last_activity_date + 1 THEN
        -- One or more calendar days were missed.
        v_current_streak := 1;
        v_last_activity_date := v_activity_date;

    ELSE
        -- An older completion must not move the streak backwards.
        NULL;
    END IF;

    v_longest_streak := GREATEST(
        v_longest_streak,
        v_current_streak
    );

    UPDATE public.streak
    SET
        current_streak = v_current_streak,
        longest_streak = v_longest_streak,
        last_activity_date = v_last_activity_date,
        updated_at = NOW()
    WHERE user_id = p_user_id;

    -- Award all newly reached streak badges.
    FOR v_badge IN
        SELECT *
        FROM public.badge
        WHERE badge_category = 'STREAK'
          AND requirement_value <= v_current_streak
          AND is_active = TRUE
        ORDER BY requirement_value
    LOOP
        INSERT INTO public.user_badge (
            user_id,
            badge_id
        )
        VALUES (
            p_user_id,
            v_badge.badge_id
        )
        ON CONFLICT (user_id, badge_id) DO NOTHING
        RETURNING user_badge_id INTO v_inserted_badge_id;

        IF FOUND THEN
            v_new_badges := v_new_badges || jsonb_build_array(
                jsonb_build_object(
                    'badge_id', v_badge.badge_id,
                    'badge_name', v_badge.badge_name,
                    'description', v_badge.description,
                    'requirement_value', v_badge.requirement_value
                )
            );
        END IF;
    END LOOP;

    -- Award newly reached streak rewards.
    FOR v_reward IN
        SELECT *
        FROM public.reward
        WHERE requirement_category = 'STREAK'
          AND requirement_value <= v_current_streak
          AND is_active = TRUE
        ORDER BY requirement_value
    LOOP
        INSERT INTO public.user_reward (
            user_id,
            reward_id
        )
        VALUES (
            p_user_id,
            v_reward.reward_id
        )
        ON CONFLICT (user_id, reward_id) DO NOTHING
        RETURNING user_reward_id INTO v_inserted_reward_id;

        IF FOUND THEN
            -- Award XP through the existing XP function.
            IF v_reward.reward_type = 'XP_BONUS'
               AND v_reward.reward_value ~ '^[0-9]+$' THEN

                SELECT
                    a.awarded,
                    a.amount
                INTO
                    v_awarded,
                    v_awarded_amount
                FROM public.award_xp(
                    p_user_id,
                    v_reward.reward_value::INTEGER,
                    'streak:' || v_reward.reward_code,
                    'Reached a ' || v_reward.requirement_value || '-day streak',
                    p_lesson_id,
                    NULL,
                    NULL,
                    v_path_id
                ) AS a;

                IF v_awarded THEN
                    v_bonus_xp := v_bonus_xp + v_awarded_amount;
                END IF;
            END IF;

            v_new_rewards := v_new_rewards || jsonb_build_array(
                jsonb_build_object(
                    'reward_id', v_reward.reward_id,
                    'reward_code', v_reward.reward_code,
                    'reward_name', v_reward.reward_name,
                    'reward_type', v_reward.reward_type,
                    'reward_value', v_reward.reward_value,
                    'requirement_value', v_reward.requirement_value
                )
            );
        END IF;
    END LOOP;

    -- Read the latest XP totals.
    SELECT overall_xp
    INTO v_overall_xp
    FROM public.user_profile
    WHERE user_id = p_user_id;

    SELECT path_xp
    INTO v_path_xp
    FROM public.enrollment
    WHERE user_id = p_user_id
      AND path_id = v_path_id;

    RETURN jsonb_build_object(
        'success', TRUE,
        'activity_date', v_activity_date,
        'lessons_completed_today', v_lessons_completed,
        'current_streak', v_current_streak,
        'longest_streak', v_longest_streak,
        'newly_earned_badges', v_new_badges,
        'newly_earned_rewards', v_new_rewards,
        'bonus_xp_awarded', v_bonus_xp,
        'overall_xp', v_overall_xp,
        'path_xp', v_path_xp
    );
END;
$$;


-- Allow the backend service role to call this function.
REVOKE ALL ON FUNCTION public.process_lesson_completion(UUID, BIGINT)
FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.process_lesson_completion(UUID, BIGINT)
TO service_role;




