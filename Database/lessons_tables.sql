-- Allow quizzes to appear as lesson sections
ALTER TABLE public.lesson_section
DROP CONSTRAINT IF EXISTS lesson_section_section_type_check;

ALTER TABLE public.lesson_section
ADD CONSTRAINT lesson_section_section_type_check
CHECK (
    section_type IN (
        'introduction',
        'text',
        'heading',
        'code',
        'example',
        'image',
        'activity',
        'callout',
        'table',
        'summary',
        'quiz'
    )
);

-- Link a quiz section to its quiz
ALTER TABLE public.lesson_section
ADD COLUMN quiz_id BIGINT UNIQUE
REFERENCES public.quiz(quiz_id)
ON DELETE CASCADE;

-- A quiz section must have a quiz; other sections must not
ALTER TABLE public.lesson_section
ADD CONSTRAINT lesson_section_quiz_link_check
CHECK (
    (section_type = 'quiz' AND quiz_id IS NOT NULL)
    OR
    (section_type <> 'quiz' AND quiz_id IS NULL)
);

COMMIT;








