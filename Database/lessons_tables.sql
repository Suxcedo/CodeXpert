
BEGIN;

-- =====================================================
-- 1. LESSONS
-- =====================================================

CREATE TABLE public.lesson (
    lesson_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id BIGINT NOT NULL
        REFERENCES public.module(module_id) ON DELETE CASCADE,
    lesson_number INTEGER NOT NULL CHECK (lesson_number > 0),
    title VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,
    summary TEXT,
    difficulty VARCHAR(20) NOT NULL DEFAULT 'beginner'
        CHECK (difficulty IN ('beginner', 'intermediate', 'advanced')),
    estimated_minutes INTEGER NOT NULL DEFAULT 15
        CHECK (estimated_minutes > 0),
    prerequisites JSONB NOT NULL DEFAULT '[]'::jsonb,
    status VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'published', 'archived')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (module_id, lesson_number)
);

-- =====================================================
-- 2. LESSON SECTIONS
-- Each section is displayed in its defined order.
-- Images are referenced by URL or local asset path.
-- =====================================================

CREATE TABLE public.lesson_section (
    section_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT NOT NULL
        REFERENCES public.lesson(lesson_id) ON DELETE CASCADE,
    display_order INTEGER NOT NULL CHECK (display_order > 0),
    section_type VARCHAR(30) NOT NULL
        CHECK (section_type IN (
            'introduction', 'text', 'heading', 'code',
            'example', 'image', 'activity', 'callout',
            'table', 'summary'
        )),
    section_title VARCHAR(200),
    section_content JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (lesson_id, display_order)
);

-- =====================================================
-- 3. QUIZZES
-- A lesson can contain multiple practice quizzes
-- and required checkpoints.
-- Module assessments use module_id instead of lesson_id.
-- =====================================================

CREATE TABLE public.quiz (
    quiz_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id BIGINT
        REFERENCES public.lesson(lesson_id) ON DELETE CASCADE,
    module_id BIGINT
        REFERENCES public.module(module_id) ON DELETE CASCADE,

    quiz_number INTEGER NOT NULL CHECK (quiz_number > 0),
    title VARCHAR(200) NOT NULL,
    instructions TEXT,

    quiz_type VARCHAR(30) NOT NULL
        CHECK (quiz_type IN (
            'practice', 'checkpoint', 'module_assessment'
        )),

    pass_mark NUMERIC(5,2) NOT NULL DEFAULT 50
        CHECK (pass_mark >= 0 AND pass_mark <= 100),

    xp_per_correct INTEGER NOT NULL DEFAULT 3
        CHECK (xp_per_correct >= 0),

    perfect_bonus_xp INTEGER NOT NULL DEFAULT 5
        CHECK (perfect_bonus_xp >= 0),

    status VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK (status IN ('draft', 'published', 'archived')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT quiz_owner_check CHECK (
        (
            quiz_type IN ('practice', 'checkpoint')
            AND lesson_id IS NOT NULL
            AND module_id IS NULL
        )
        OR
        (
            quiz_type = 'module_assessment'
            AND module_id IS NOT NULL
            AND lesson_id IS NULL
        )
    )
);

CREATE UNIQUE INDEX idx_quiz_lesson_number
    ON public.quiz(lesson_id, quiz_number)
    WHERE lesson_id IS NOT NULL;

CREATE UNIQUE INDEX idx_one_module_assessment
    ON public.quiz(module_id)
    WHERE quiz_type = 'module_assessment';

-- =====================================================
-- 4. QUESTIONS
-- evaluation contains the correct answer and marking rules.
-- The backend must not expose evaluation to the frontend.
-- =====================================================

CREATE TABLE public.question (
    question_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id BIGINT NOT NULL
        REFERENCES public.quiz(quiz_id) ON DELETE CASCADE,
    display_order INTEGER NOT NULL CHECK (display_order > 0),

    question_type VARCHAR(30) NOT NULL
        CHECK (question_type IN (
            'multiple_choice', 'true_false', 'short_answer'
        )),

    prompt TEXT NOT NULL,
    options JSONB NOT NULL DEFAULT '[]'::jsonb,
    evaluation JSONB NOT NULL DEFAULT '{}'::jsonb,
    explanation TEXT,

    xp_reward INTEGER NOT NULL DEFAULT 3
        CHECK (xp_reward >= 0),

    is_required BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (quiz_id, display_order),
    UNIQUE (question_id, quiz_id)
);

-- =====================================================
-- 5. LESSON PROGRESS
-- =====================================================

CREATE TABLE public.lesson_progress (
    progress_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id) ON DELETE CASCADE,
    lesson_id BIGINT NOT NULL
        REFERENCES public.lesson(lesson_id) ON DELETE CASCADE,

    status VARCHAR(20) NOT NULL DEFAULT 'not_started'
        CHECK (status IN ('not_started', 'in_progress', 'completed')),

    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (user_id, lesson_id)
);

-- =====================================================
-- 6. SECTION PROGRESS
-- A section stays locked until its requirements are met.
-- =====================================================

CREATE TABLE public.lesson_section_progress (
    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id) ON DELETE CASCADE,
    section_id BIGINT NOT NULL
        REFERENCES public.lesson_section(section_id) ON DELETE CASCADE,

    completed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (user_id, section_id)
);

-- =====================================================
-- 7. QUIZ ATTEMPTS
-- Every retry creates a separate attempt.
-- =====================================================

CREATE TABLE public.quiz_attempt (
    quiz_attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id) ON DELETE CASCADE,
    quiz_id BIGINT NOT NULL
        REFERENCES public.quiz(quiz_id) ON DELETE CASCADE,

    attempt_number INTEGER NOT NULL CHECK (attempt_number > 0),
    score NUMERIC(5,2) NOT NULL DEFAULT 0
        CHECK (score >= 0 AND score <= 100),

    total_questions INTEGER NOT NULL DEFAULT 0
        CHECK (total_questions >= 0),
    correct_answers INTEGER NOT NULL DEFAULT 0
        CHECK (
            correct_answers >= 0
            AND correct_answers <= total_questions
        ),

    passed BOOLEAN NOT NULL DEFAULT FALSE,
    is_perfect BOOLEAN NOT NULL DEFAULT FALSE,

    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    submitted_at TIMESTAMPTZ,

    UNIQUE (user_id, quiz_id, attempt_number),
    UNIQUE (quiz_attempt_id, quiz_id)
);

-- =====================================================
-- 8. QUESTION ATTEMPTS
-- Each question can be answered once within an attempt.
-- Retrying the quiz creates a new quiz attempt.
-- =====================================================

CREATE TABLE public.question_attempt (
    question_attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    quiz_attempt_id BIGINT NOT NULL,
    quiz_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,

    submitted_answer JSONB NOT NULL,
    is_correct BOOLEAN NOT NULL,
    xp_awarded INTEGER NOT NULL DEFAULT 0
        CHECK (xp_awarded >= 0),

    answered_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    FOREIGN KEY (quiz_attempt_id, quiz_id)
        REFERENCES public.quiz_attempt(quiz_attempt_id, quiz_id)
        ON DELETE CASCADE,

    FOREIGN KEY (question_id, quiz_id)
        REFERENCES public.question(question_id, quiz_id)
        ON DELETE CASCADE,

    UNIQUE (quiz_attempt_id, question_id),
    UNIQUE (question_attempt_id, quiz_attempt_id)
);

-- =====================================================
-- 9. XP TRANSACTIONS
-- reward_key prevents the same reward being issued twice
-- to the same user.
-- =====================================================

CREATE TABLE public.xp_transaction (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id) ON DELETE CASCADE,

    lesson_id BIGINT
        REFERENCES public.lesson(lesson_id) ON DELETE SET NULL,

    quiz_attempt_id BIGINT,
    question_attempt_id BIGINT,

    reward_key VARCHAR(200) NOT NULL,
    amount INTEGER NOT NULL CHECK (amount > 0),
    reason VARCHAR(100) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    FOREIGN KEY (question_attempt_id, quiz_attempt_id)
        REFERENCES public.question_attempt(
            question_attempt_id, quiz_attempt_id
        )
        ON DELETE SET NULL,

    UNIQUE (user_id, reward_key)
);

-- =====================================================
-- 10. MODULE CHECKLIST
-- =====================================================

CREATE TABLE public.module_checklist_item (
    checklist_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    module_id BIGINT NOT NULL
        REFERENCES public.module(module_id) ON DELETE CASCADE,

    display_order INTEGER NOT NULL CHECK (display_order > 0),
    item_text TEXT NOT NULL,

    UNIQUE (module_id, display_order)
);

CREATE TABLE public.module_checklist_progress (
    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id) ON DELETE CASCADE,

    checklist_item_id BIGINT NOT NULL
        REFERENCES public.module_checklist_item(checklist_item_id)
        ON DELETE CASCADE,

    completed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (user_id, checklist_item_id)
);

-- =====================================================
-- 11. INDEXES
-- =====================================================

CREATE INDEX idx_lesson_module
    ON public.lesson(module_id, lesson_number);

CREATE INDEX idx_section_lesson_order
    ON public.lesson_section(lesson_id, display_order);

CREATE INDEX idx_question_quiz_order
    ON public.question(quiz_id, display_order);

CREATE INDEX idx_quiz_attempt_user
    ON public.quiz_attempt(user_id, quiz_id, attempt_number);

CREATE INDEX idx_question_attempt_user
    ON public.question_attempt(quiz_attempt_id);

CREATE INDEX idx_lesson_progress_user
    ON public.lesson_progress(user_id, status);

CREATE INDEX idx_xp_transaction_user
    ON public.xp_transaction(user_id, created_at);

CREATE INDEX idx_checklist_progress_user
    ON public.module_checklist_progress(user_id);

COMMIT;






