
BEGIN;

-- =========================================
-- 1. COMMUNITY GROUP
-- One group for each learning path
-- =========================================

CREATE TABLE public.community_group (
    group_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    path_id BIGINT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_community_group_path
        FOREIGN KEY (path_id)
        REFERENCES public.learning_path(path_id)
        ON DELETE CASCADE
);


-- =========================================
-- 2. GROUP MEMBER
-- Stores group membership and read tracking
-- =========================================

CREATE TABLE public.group_member (
    member_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    user_id UUID NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_read_at TIMESTAMPTZ,

    CONSTRAINT fk_group_member_group
        FOREIGN KEY (group_id)
        REFERENCES public.community_group(group_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_group_member_user
        FOREIGN KEY (user_id)
        REFERENCES public.user_profile(user_id)
        ON DELETE CASCADE,

    CONSTRAINT unique_group_member
        UNIQUE (group_id, user_id)
);


-- =========================================
-- 3. GROUP MESSAGE
-- Stores messages sent in community groups
-- =========================================

CREATE TABLE public.group_message (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL,
    user_id UUID,
    message_text TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,

    CONSTRAINT fk_group_message_group
        FOREIGN KEY (group_id)
        REFERENCES public.community_group(group_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_group_message_user
        FOREIGN KEY (user_id)
        REFERENCES public.user_profile(user_id)
        ON DELETE SET NULL,

    CONSTRAINT valid_message_length
        CHECK (LENGTH(TRIM(message_text)) BETWEEN 1 AND 2000),

    CONSTRAINT valid_message_deletion
        CHECK (
            (is_deleted = FALSE AND deleted_at IS NULL)
            OR
            (is_deleted = TRUE AND deleted_at IS NOT NULL)
        )
);


-- =========================================
-- 4. NOTIFICATION
-- Central notification table for CodeXperts
-- Supports community now and Reels later
-- =========================================

CREATE TABLE public.notification (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL,
    actor_user_id UUID,
    notification_type VARCHAR(50) NOT NULL,
    title VARCHAR(150) NOT NULL,
    message TEXT NOT NULL,
    reference_type VARCHAR(50),
    reference_id BIGINT,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_notification_recipient
        FOREIGN KEY (user_id)
        REFERENCES public.user_profile(user_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_notification_actor
        FOREIGN KEY (actor_user_id)
        REFERENCES public.user_profile(user_id)
        ON DELETE SET NULL
);


-- =========================================
-- 5. INDEXES
-- Improve query performance
-- =========================================

CREATE INDEX idx_group_member_user
    ON public.group_member(user_id);

CREATE INDEX idx_group_member_group
    ON public.group_member(group_id);

CREATE INDEX idx_group_message_group_created
    ON public.group_message(group_id, created_at);

CREATE INDEX idx_notification_user_created
    ON public.notification(user_id, created_at DESC);

CREATE INDEX idx_notification_unread
    ON public.notification(user_id, is_read);


