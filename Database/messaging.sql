-- =========================================
-- 11. AUTOMATIC GROUP CREATION
-- Create a group when a learning path is added
-- =========================================

CREATE FUNCTION public.create_community_group()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.community_group (path_id)
    VALUES (NEW.path_id);

    RETURN NEW;
END;
$$;


CREATE TRIGGER trg_create_community_group
AFTER INSERT ON public.learning_path
FOR EACH ROW
EXECUTE FUNCTION public.create_community_group();


-- =========================================
-- 12. AUTOMATIC MEMBERSHIP
-- Add users when they actively enrol
-- =========================================

CREATE FUNCTION public.add_community_group_member()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_group_id BIGINT;
BEGIN
    IF NEW.status = 'active' THEN

        SELECT group_id
        INTO v_group_id
        FROM public.community_group
        WHERE path_id = NEW.path_id;

        IF v_group_id IS NOT NULL THEN
            INSERT INTO public.group_member (group_id, user_id)
            VALUES (v_group_id, NEW.user_id)
            ON CONFLICT (group_id, user_id) DO NOTHING;
        END IF;

    END IF;

    RETURN NEW;
END;
$$;


CREATE TRIGGER trg_add_community_group_member
AFTER INSERT OR UPDATE OF status, path_id, user_id
ON public.enrollment
FOR EACH ROW
EXECUTE FUNCTION public.add_community_group_member();


-- =========================================
-- 13. AUTOMATIC COMMUNITY NOTIFICATIONS
-- Notify other active enrollees when a message
-- is sent in their learning path group
-- =========================================

CREATE FUNCTION public.notify_community_message()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    v_path_id BIGINT;
    v_path_name VARCHAR(255);
    v_username VARCHAR(255);
BEGIN

    IF NEW.user_id IS NULL THEN
        RETURN NEW;
    END IF;

    SELECT cg.path_id, lp.path_name
    INTO v_path_id, v_path_name
    FROM public.community_group cg
    JOIN public.learning_path lp
      ON lp.path_id = cg.path_id
    WHERE cg.group_id = NEW.group_id;

    SELECT username
    INTO v_username
    FROM public.user_profile
    WHERE user_id = NEW.user_id;

    INSERT INTO public.notification (
        user_id,
        actor_user_id,
        notification_type,
        title,
        message,
        reference_type,
        reference_id
    )
    SELECT
        e.user_id,
        NEW.user_id,
        'new_message',
        'New message in ' || v_path_name,
        COALESCE(v_username, 'A member') || ' sent a message.',
        'group_message',
        NEW.message_id
    FROM public.enrollment e
    WHERE e.path_id = v_path_id
      AND e.status = 'active'
      AND e.user_id <> NEW.user_id;

    RETURN NEW;
END;
$$;


CREATE TRIGGER trg_notify_community_message
AFTER INSERT ON public.group_message
FOR EACH ROW
EXECUTE FUNCTION public.notify_community_message();


