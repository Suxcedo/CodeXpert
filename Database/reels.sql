
-- =====================================================
-- CODEXPERTS REELS DATABASE IMPLEMENTATION
-- Creates four new tables and adds a profile bio column
-- =====================================================

-- 1. ADD BIO TO EXISTING USER PROFILE
ALTER TABLE public.user_profile
ADD COLUMN IF NOT EXISTS bio VARCHAR(300);


-- =====================================================
-- 2. VIDEO TABLE
-- Stores uploaded Reel information
-- =====================================================

CREATE TABLE IF NOT EXISTS public.video (
    video_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id)
        ON DELETE CASCADE,

    video_url TEXT NOT NULL,

    cloudinary_public_id TEXT NOT NULL UNIQUE,

    thumbnail_url TEXT,

    caption VARCHAR(2200),

    duration_seconds INTEGER,

    status VARCHAR(20) NOT NULL DEFAULT 'published',

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT video_duration_check
        CHECK (duration_seconds IS NULL OR duration_seconds > 0),

    CONSTRAINT video_status_check
        CHECK (status IN ('draft', 'published', 'hidden'))
);


-- =====================================================
-- 3. VIDEO_LIKE TABLE
-- Stores users who like Reels
-- =====================================================

CREATE TABLE IF NOT EXISTS public.video_like (
    video_id BIGINT NOT NULL
        REFERENCES public.video(video_id)
        ON DELETE CASCADE,

    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id)
        ON DELETE CASCADE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (video_id, user_id)
);


-- =====================================================
-- 4. VIDEO_COMMENT TABLE
-- Stores comments on Reels
-- =====================================================

CREATE TABLE IF NOT EXISTS public.video_comment (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    video_id BIGINT NOT NULL
        REFERENCES public.video(video_id)
        ON DELETE CASCADE,

    user_id UUID NOT NULL
        REFERENCES public.user_profile(user_id)
        ON DELETE CASCADE,

    comment_text VARCHAR(1000) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT video_comment_not_empty
        CHECK (LENGTH(TRIM(comment_text)) > 0)
);


-- =====================================================
-- 5. USER_FOLLOW TABLE
-- Stores follower and following relationships
-- =====================================================

CREATE TABLE IF NOT EXISTS public.user_follow (
    follow_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    follower_id UUID NOT NULL
        REFERENCES public.user_profile(user_id)
        ON DELETE CASCADE,

    following_id UUID NOT NULL
        REFERENCES public.user_profile(user_id)
        ON DELETE CASCADE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT unique_user_follow
        UNIQUE (follower_id, following_id),

    CONSTRAINT prevent_self_follow
        CHECK (follower_id <> following_id)
);


-- =====================================================
-- 6. CREATE INDEXES FOR BETTER QUERY PERFORMANCE
-- =====================================================

CREATE INDEX IF NOT EXISTS idx_video_published_feed
ON public.video (created_at DESC)
WHERE status = 'published';

CREATE INDEX IF NOT EXISTS idx_video_user
ON public.video (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_video_like_user
ON public.video_like (user_id);

CREATE INDEX IF NOT EXISTS idx_video_comment_video
ON public.video_comment (video_id, created_at DESC);

CREATE INDEX IF NOT EXISTS idx_video_comment_user
ON public.video_comment (user_id);

CREATE INDEX IF NOT EXISTS idx_user_follow_follower
ON public.user_follow (follower_id);

CREATE INDEX IF NOT EXISTS idx_user_follow_following
ON public.user_follow (following_id);


-- =====================================================
-- 7. ENABLE ROW LEVEL SECURITY
-- =====================================================

ALTER TABLE public.video ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.video_like ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.video_comment ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_follow ENABLE ROW LEVEL SECURITY;


-- =====================================================
-- 8. VIDEO SECURITY POLICIES
-- =====================================================

CREATE POLICY "Authenticated users can view published videos"
ON public.video
FOR SELECT
TO authenticated
USING (
    status = 'published'
    OR user_id = (SELECT auth.uid())
);

CREATE POLICY "Users can upload their own videos"
ON public.video
FOR INSERT
TO authenticated
WITH CHECK (
    user_id = (SELECT auth.uid())
);

CREATE POLICY "Users can update their own videos"
ON public.video
FOR UPDATE
TO authenticated
USING (
    user_id = (SELECT auth.uid())
)
WITH CHECK (
    user_id = (SELECT auth.uid())
);

CREATE POLICY "Users can delete their own videos"
ON public.video
FOR DELETE
TO authenticated
USING (
    user_id = (SELECT auth.uid())
);


-- =====================================================
-- 9. VIDEO LIKE SECURITY POLICIES
-- =====================================================

CREATE POLICY "Users can view likes on accessible videos"
ON public.video_like
FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.video v
        WHERE v.video_id = video_like.video_id
        AND (
            v.status = 'published'
            OR v.user_id = (SELECT auth.uid())
        )
    )
);

CREATE POLICY "Users can like published videos"
ON public.video_like
FOR INSERT
TO authenticated
WITH CHECK (
    user_id = (SELECT auth.uid())
    AND EXISTS (
        SELECT 1
        FROM public.video v
        WHERE v.video_id = video_like.video_id
        AND v.status = 'published'
    )
);

CREATE POLICY "Users can remove their own likes"
ON public.video_like
FOR DELETE
TO authenticated
USING (
    user_id = (SELECT auth.uid())
);


-- =====================================================
-- 10. VIDEO COMMENT SECURITY POLICIES
-- =====================================================

CREATE POLICY "Users can view comments on accessible videos"
ON public.video_comment
FOR SELECT
TO authenticated
USING (
    EXISTS (
        SELECT 1
        FROM public.video v
        WHERE v.video_id = video_comment.video_id
        AND (
            v.status = 'published'
            OR v.user_id = (SELECT auth.uid())
        )
    )
);

CREATE POLICY "Users can comment on published videos"
ON public.video_comment
FOR INSERT
TO authenticated
WITH CHECK (
    user_id = (SELECT auth.uid())
    AND EXISTS (
        SELECT 1
        FROM public.video v
        WHERE v.video_id = video_comment.video_id
        AND v.status = 'published'
    )
);

CREATE POLICY "Users can update their own comments"
ON public.video_comment
FOR UPDATE
TO authenticated
USING (
    user_id = (SELECT auth.uid())
)
WITH CHECK (
    user_id = (SELECT auth.uid())
);

CREATE POLICY "Users can delete their own comments"
ON public.video_comment
FOR DELETE
TO authenticated
USING (
    user_id = (SELECT auth.uid())
);


-- =====================================================
-- 11. USER FOLLOW SECURITY POLICIES
-- =====================================================

CREATE POLICY "Authenticated users can view follow relationships"
ON public.user_follow
FOR SELECT
TO authenticated
USING (TRUE);

CREATE POLICY "Users can follow other users"
ON public.user_follow
FOR INSERT
TO authenticated
WITH CHECK (
    follower_id = (SELECT auth.uid())
    AND follower_id <> following_id
);

CREATE POLICY "Users can unfollow other users"
ON public.user_follow
FOR DELETE
TO authenticated
USING (
    follower_id = (SELECT auth.uid())
);


